/**
 * Bundle the Hono API into a single ESM file for Vercel.
 * Avoids ERR_MODULE_NOT_FOUND when the serverless function imports ../server/*.ts.
 */
import * as esbuild from "esbuild";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outfile = join(root, "api", "app.mjs");

await esbuild.build({
  absWorkingDir: root,
  entryPoints: [join(root, "server", "app.ts")],
  outfile,
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  sourcemap: false,
  logLevel: "info",
  // Bundle app + deps so Vercel doesn't need to resolve ../server/*.ts imports.
  banner: {
    js: "/* BiteRate API bundle — generated by scripts/build-api.mjs */",
  },
});

console.log(`api bundle → ${outfile}`);
